/**
 * npm run simulate:robot: record simulated episodes, learn, deploy every condition, sweep the key
 * assumptions, print the results and write docs/ROBOT_VIEW_RESULTS.md.
 */

import { writeFileSync } from "node:fs";
import { DEFAULT_PARAMS } from "../src/robot/sim/params";
import { LABEL_NAMES, LABEL_SOURCES } from "../src/robot/learn/detector";
import { GAZE_FEATURES } from "../src/robot/learn/gazePolicy";
import { SWEEP_RECORDED, learningCurves, runStudy, sweep, type Metrics } from "../src/robot/learn/experiment";

const CAVEAT = "These numbers come from toy physics and simulated signals. They illustrate a mechanism and are not evidence.";
const pct = (v: number) => `${(v * 100).toFixed(1)}%`;
const sec = (v: number | null) => (v === null ? "n/a" : `${v.toFixed(2)} s`);

const t0 = Date.now();
const study = runStudy(DEFAULT_PARAMS, 120, 200);
const curves = learningCurves(DEFAULT_PARAMS, study.recordings, study.gaze.policy);
const sw = sweep(DEFAULT_PARAMS, study.gaze.policy);

const rec = study.recordings;
const teleop = rec.filter((e) => e.mode === "teleop").length;
const failures = rec.filter((e) => e.outcome !== "intact").length;
const notices = rec.reduce((s, e) => s + e.notices.length, 0);
const detected = rec.reduce((s, e) => s + e.errp.filter((x) => x.detected && !x.falseAlarm).length, 0);
const falseAlarms = rec.reduce((s, e) => s + e.errp.filter((x) => x.falseAlarm).length, 0);
const hits = study.gaze.hitByEpisode.filter(Number.isFinite);
const hitFirst = hits.slice(0, 10).reduce((s, v) => s + v, 0) / Math.min(10, hits.length);
const hitLast = hits.slice(-20).reduce((s, v) => s + v, 0) / Math.min(20, hits.length);

const tableRows = (rows: Metrics[]) =>
  rows.map((r) => `| ${r.label} | ${r.tokens} | ${pct(r.success)} | ${pct(r.crush)} | ${pct(r.drop)} | ${sec(r.medianLead)} | ${pct(r.falseCorrection)} |`).join("\n");

const md = `# Aska Robot View: simulated results

**Simulation. Not a product demo.** ${CAVEAT}

Generated by \`npm run simulate:robot\` with fixed seeds. Model and assumptions: [ROBOT_VIEW_MODEL.md](ROBOT_VIEW_MODEL.md).

## Recording (simulated)

- ${rec.length} episodes: ${teleop} teleoperated (the person corrects problems) and ${rec.length - teleop} watched (the robot runs its cloned policy; the person only watches).
- ${notices} problems noticed by the simulated person; ${detected} error responses caught by the simulated decoder (hit rate ${DEFAULT_PARAMS.pHit}), plus ${falseAlarms} false alarms.
- ${failures} episodes ended in a crush or a drop, which is all the outcome labels have to learn from.

## Where to look: learned gaze policy

Next-fixation hit rate (inside the predicted 4 x 4 fovea box), predicted before each update: ${pct(hitFirst)} over the first 10 episodes, ${pct(hitLast)} over the last 20.

Learned weights: ${GAZE_FEATURES.map((f, i) => `${f} ${study.gaze.policy.w[i].toFixed(2)}`).join("; ")}.

## Deployment, ${study.deploySeeds.length} episodes per condition, distractors on, no human in the loop

| Condition | Vision tokens / frame | Success | Crushed | Dropped | Median detection lead | False corrections |
|---|---|---|---|---|---|---|
${tableRows(study.rows)}

Detection lead is how long before the failure (that would have happened without a correction) the detector fired. False corrections are the share of would-be-fine episodes where it fired anyway.

## Learning curves (learned gaze, 100 deployment episodes)

| Recorded episodes | ${LABEL_SOURCES.map((s) => LABEL_NAMES[s]).join(" | ")} |
|---|${LABEL_SOURCES.map(() => "---").join("|")}|
${curves.map((c) => `| ${c.episodes} | ${LABEL_SOURCES.map((s) => (c.bySource[s].trained ? `${pct(c.bySource[s].success)} success, lead ${sec(c.bySource[s].medianLead)}` : "no positive labels yet")).join(" | ")} |`).join("\n")}

## Sensitivity sweep: learned foveation + EEG labels versus uniform + outcome labels, trained on ${SWEEP_RECORDED} recorded episodes (success rate)

${sw
  .map(
    (s) => `**${s.label}**\n\n| Value | Aska | Baseline | Difference |\n|---|---|---|---|\n${s.points
      .map((p) => `| ${p.value}${s.unit ? " " + s.unit : ""} | ${pct(p.aska)} | ${pct(p.baseline)} | ${((p.aska - p.baseline) * 100).toFixed(1)} pts |`)
      .join("\n")}`,
  )
  .join("\n\n")}

## How to read this

- Foveation buys compute (20 versus 324 tokens) and robustness to distractors. It does not make the robot see better than the uniform encoder, which sees everything at full resolution.
- With 120 recorded episodes, outcome labels catch up: enough real failures happen in watched episodes to teach the same pattern, because a crush has a simple, steady signature here. EEG's advantage in this simulation is narrow: the EEG-trained detector works after 5 to 10 recorded episodes, before outcome labels have enough failures, and it fires a little earlier.
- The sweep (20 recorded episodes) shows EEG labels are the more fragile source. With a decoder hit rate of 0.65 or below, or when people notice squash very early (0.03) or very late (0.2), the EEG-trained detector does worse than the outcome-trained baseline.
- In teleoperation, the operator's own corrections already mark most problems, so correction labels and EEG labels end up close. EEG's distinct value is in episodes where nobody corrects, such as a person watching the robot run on its own.
- The EEG advantage depends on people noticing problems before they become irreversible and on the decoder catching that noticing. The sweep shows how fast it fades when those assumptions weaken.

${CAVEAT}
`;

writeFileSync(new URL("../docs/ROBOT_VIEW_RESULTS.md", import.meta.url), md);

// precomputed results and trained models for robot.html
const model = (m: (typeof study.detectors)["eeg"]) => (m ? { mean: m.mean, std: m.std, w: m.w, b: m.b, threshold: m.threshold } : null);
writeFileSync(
  new URL("../public/robot-results.json", import.meta.url),
  JSON.stringify({
    caveat: CAVEAT,
    params: DEFAULT_PARAMS,
    recording: { episodes: rec.length, teleop, watched: rec.length - teleop, notices, decoded: detected, falseAlarms, failures },
    gaze: { weights: study.gaze.policy.w, hitByEpisode: study.gaze.hitByEpisode },
    detectors: { outcome: model(study.detectors.outcome), correction: model(study.detectors.correction), eeg: model(study.detectors.eeg) },
    rows: study.rows,
    curves,
    sweep: sw,
  }),
);

console.log(`\nAska Robot View, simulated (${((Date.now() - t0) / 1000).toFixed(1)} s)\n${CAVEAT}\n`);
console.log(`Recording: ${rec.length} episodes (${teleop} teleop, ${rec.length - teleop} watched), ${notices} problems noticed, ${detected} error responses decoded, ${falseAlarms} false alarms, ${failures} actual failures.`);
console.log(`Gaze policy hit rate: ${pct(hitFirst)} first 10 episodes, ${pct(hitLast)} last 20.\n`);
console.log("condition".padEnd(78) + "tokens  success  crushed  dropped  lead     false corr.");
for (const r of study.rows) {
  console.log(`${r.label.padEnd(78)}${String(r.tokens).padStart(6)}  ${pct(r.success).padStart(7)}  ${pct(r.crush).padStart(7)}  ${pct(r.drop).padStart(7)}  ${sec(r.medianLead).padStart(7)}  ${pct(r.falseCorrection).padStart(7)}`);
}
console.log("\nSweep (success, Aska vs baseline):");
for (const s of sw) console.log(`  ${s.label}: ` + s.points.map((p) => `${p.value}: ${pct(p.aska)} vs ${pct(p.baseline)}`).join(" | "));
console.log("\nWrote docs/ROBOT_VIEW_RESULTS.md and public/robot-results.json");
